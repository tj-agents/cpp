#!/usr/bin/env python3
"""Generate the C++ skill-route table consumed by agent-process's write hook."""

import argparse
import json
import tempfile
from pathlib import Path


CPP_PATH = r"\.(c|cc|cpp|cxx|h|hh|hpp|hxx|ixx)$"
BUILD_PATH = r"(^|/)(CMakeLists\.txt|CMakePresets\.json|[^/]+\.cmake)$"
TEST_PATH = r"(^|/)(tests?|test)/.*\.(c|cc|cpp|cxx|h|hh|hpp|hxx)$|(_test|_tests)\.(c|cc|cpp|cxx)$"


def routes(kind: str) -> dict:
    result = [
        {
            "path": CPP_PATH,
            "skills": ["cpp-standards:cpp-style"],
            "note": "C++ source floor. More specific routes add to this skill; they do not replace it.",
        },
        {
            "path": BUILD_PATH,
            "skills": ["cpp-standards:cpp-build", "cpp-standards:cpp-libraries"],
        },
        {
            "path": TEST_PATH,
            "skills": ["cpp-standards:cpp-testing"],
        },
        {
            "path": r"(^|/)(AGENTS|CLAUDE)\.md$",
            "skills": ["agent-process:docs-and-debt"],
        },
        {
            "path": r"^\.agents/skill-routes\.json$",
            "skills": ["agent-process:skill-routes"],
        },
    ]

    if kind == "gpp":
        result.append(
            {
                "path": rf"{CPP_PATH}|{BUILD_PATH}",
                "skills": ["gpp-standards:gpp-toolchain"],
                "note": "GNU/Linux toolchain layer generated for a gpp project.",
            }
        )
    elif kind == "windows":
        result.extend(
            [
                {
                    "path": rf"{CPP_PATH}|\.(rc|manifest)$",
                    "skills": [
                        "windows-standards:windows-overview",
                        "windows-standards:win32-style",
                    ],
                    "note": "Native Windows layer generated for an MSVC/Win32 project.",
                },
                {
                    "path": BUILD_PATH,
                    "skills": ["windows-standards:windows-overview"],
                },
            ]
        )

    return {
        "_comment": [
            "Generated by tomjseery/cpp-agents .agents/gen_skill_routes.py; do not edit by hand.",
            "The agent-process plugin reads this table before writes and reviews.",
            "Every matching route fires, so platform and test/build routes layer on the C++ floor.",
        ],
        "kind": kind,
        "routes": result,
    }


def rendered(kind: str) -> str:
    return json.dumps(routes(kind), indent=2, ensure_ascii=False) + "\n"


def target_for(root: Path) -> Path:
    return root / ".agents" / "skill-routes.json"


def write_or_check(kind: str, root: Path, check: bool) -> int:
    target = target_for(root)
    expected = rendered(kind)
    if check:
        try:
            actual = target.read_text(encoding="utf-8")
        except OSError:
            actual = None
        if actual != expected:
            print(f"STALE: {target}; regenerate with --kind {kind} --into {root}")
            return 1
        print(f"current: {target} ({kind})")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"generated: {target} ({kind})")
    return 0


def self_test() -> int:
    with tempfile.TemporaryDirectory() as temporary:
        root = Path(temporary)
        for kind in ("portable", "gpp", "windows"):
            destination = root / kind
            if write_or_check(kind, destination, False) != 0:
                return 1
            if write_or_check(kind, destination, True) != 0:
                return 1
            parsed = json.loads(target_for(destination).read_text(encoding="utf-8"))
            if parsed["kind"] != kind or not parsed["routes"]:
                return 1
    print("skill-route generator self-test passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--kind", choices=("portable", "gpp", "windows"))
    parser.add_argument("--into", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        if args.kind or args.into or args.check:
            parser.error("--self-test cannot be combined with generation arguments")
        return self_test()
    if not args.kind or not args.into:
        parser.error("--kind and --into are required unless --self-test is used")
    return write_or_check(args.kind, args.into.resolve(), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
