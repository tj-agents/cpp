#!/usr/bin/env python3
"""Generate independent C++ toolchain and API skill routes."""

from __future__ import annotations

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path
from typing import NotRequired, TypedDict

MINIMUM_PYTHON = (3, 12)

if sys.version_info < MINIMUM_PYTHON:
    raise SystemExit("Python 3.12 or newer is required")


class Route(TypedDict):
    path: str
    skills: list[str]
    note: NotRequired[str]


class RoutePayload(TypedDict):
    _comment: list[str]
    profile: dict[str, str | list[str] | None]
    layers: list[str]
    routes: list[Route]


CPP_PATH = r"(?i:\.(c|cc|cpp|cxx|h|hh|hpp|hxx|ixx))$"
BUILD_PATH = r"(?i:(^|/)(CMakeLists\.txt|CMakePresets\.json|[^/]+\.cmake))$"
TEST_PATH = (
    "(?i:(^|/)(tests?|test)/.*\\.(c|cc|cpp|cxx|h|hh|hpp|hxx)|(_tes"
    "t|_tests)\\.(c|cc|cpp|cxx))$"
)
WINDOWS_RESOURCE_PATH = r"(?i:\.(rc|manifest))$"
MSVC_BUILD_PATH = r"(?i:\.(vcxproj|props|targets|sln|slnx))$"
TOOLCHAINS = ("gpp", "msvc")
APIS = ("win32",)


def normalize(
    toolchain: str | None = None, apis: list[str] | tuple[str, ...] = ()
) -> tuple[str | None, tuple[str, ...]]:
    if toolchain not in (None, *TOOLCHAINS):
        raise ValueError(f"unknown toolchain: {toolchain}")
    unknown = set(apis) - set(APIS)
    if unknown:
        raise ValueError(f"unknown API selection(s): {', '.join(sorted(unknown))}")
    return toolchain, tuple(api for api in APIS if api in apis)


def routes(
    toolchain: str | None = None, apis: list[str] | tuple[str, ...] = ()
) -> RoutePayload:
    toolchain, apis = normalize(toolchain, apis)
    result: list[Route] = [
        {
            "path": CPP_PATH,
            "skills": ["cpp:style", "cpp:domain-design", "cpp:mixins", "cpp:structure"],
            "note": (
                "C++ style, data and invariant design, behavior composition, "
                "and project structure."
            ),
        },
        {"path": BUILD_PATH, "skills": ["cpp:build", "cpp:structure", "cpp:libraries"]},
        {"path": TEST_PATH, "skills": ["cpp:testing"]},
    ]
    if toolchain == "gpp":
        result.append(
            {
                "path": rf"{CPP_PATH}|{BUILD_PATH}",
                "skills": ["gpp:toolchain"],
                "note": "Explicit G++ toolchain selection.",
            }
        )
    if toolchain == "msvc":
        result.append(
            {
                "path": rf"{CPP_PATH}|{BUILD_PATH}|{MSVC_BUILD_PATH}",
                "skills": ["msvc:toolchain"],
                "note": "Explicit MSVC/clang-cl toolchain selection.",
            }
        )
    if "win32" in apis:
        result.append(
            {
                "path": (
                    rf"{CPP_PATH}|{BUILD_PATH}|{MSVC_BUILD_PATH}|"
                    rf"{WINDOWS_RESOURCE_PATH}"
                ),
                "skills": ["win32:overview", "win32:style"],
                "note": (
                    "Explicit user-mode Win32 API selection; compiler remains "
                    "independent."
                ),
            }
        )
    layers = ["cpp", *([toolchain] if toolchain else []), *apis]
    return {
        "_comment": [
            (
                "Generated by tj-agents/cpp scripts/gen_skill_routes.py; do "
                "not edit by hand."
            ),
            (
                "Toolchain and API selections are independent. Host OS never "
                "chooses a compiler."
            ),
            "Every matching technical route fires; no process plugin is required.",
        ],
        "profile": {"toolchain": toolchain, "apis": list(apis)},
        "layers": layers,
        "routes": result,
    }


def rendered(
    toolchain: str | None = None, apis: list[str] | tuple[str, ...] = ()
) -> str:
    return json.dumps(routes(toolchain, apis), indent=2, ensure_ascii=False) + "\n"


def target_for(root: Path) -> Path:
    return root / ".agents" / "skill-routes.json"


def skills_for(
    toolchain: str | None, apis: list[str] | tuple[str, ...], path: str
) -> set[str]:
    matched: set[str] = set()
    for route in routes(toolchain, apis)["routes"]:
        if re.search(route["path"], path):
            matched.update(route.get("skills") or [])
    return matched


def write_or_check(
    toolchain: str | None, apis: list[str], root: Path, check: bool
) -> int:
    target = target_for(root)
    expected = rendered(toolchain, apis)
    if check:
        actual = target.read_text(encoding="utf-8") if target.is_file() else None
        if actual != expected:
            print(f"STALE: {target}")
            return 1
        print(f"current: {target}")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(expected, encoding="utf-8", newline="\n")
    print(f"generated: {target} ({'+'.join(routes(toolchain, apis)['layers'])})")
    return 0


def self_test() -> int:
    profiles: list[tuple[str | None, list[str]]] = [
        (None, []),
        ("gpp", []),
        ("msvc", []),
        (None, ["win32"]),
        ("gpp", ["win32"]),
        ("msvc", ["win32"]),
    ]
    with tempfile.TemporaryDirectory() as temporary:
        for index, (toolchain, apis) in enumerate(profiles):
            root = Path(temporary) / str(index)
            if write_or_check(toolchain, apis, root, False) or write_or_check(
                toolchain, apis, root, True
            ):
                return 1
    cases = {
        ((None, ()), "src/main.cpp"): {
            "cpp:style",
            "cpp:domain-design",
            "cpp:mixins",
            "cpp:structure",
        },
        (("msvc", ()), "src/main.cpp"): {
            "cpp:style",
            "cpp:domain-design",
            "cpp:mixins",
            "cpp:structure",
            "msvc:toolchain",
        },
        (("msvc", ()), "app/app.rc"): set(),
        ((None, ("win32",)), "src/main.cpp"): {
            "cpp:style",
            "cpp:domain-design",
            "cpp:mixins",
            "cpp:structure",
            "win32:overview",
            "win32:style",
        },
        ((None, ("win32",)), "app/app.vcxproj"): {"win32:overview", "win32:style"},
        ((None, ("win32",)), "CMakeLists.txt"): {
            "cpp:build",
            "cpp:structure",
            "cpp:libraries",
            "win32:overview",
            "win32:style",
        },
        (("gpp", ("win32",)), "src/main.cpp"): {
            "cpp:style",
            "cpp:domain-design",
            "cpp:mixins",
            "cpp:structure",
            "gpp:toolchain",
            "win32:overview",
            "win32:style",
        },
        ((None, ()), "tests/core_test.cpp"): {
            "cpp:style",
            "cpp:domain-design",
            "cpp:mixins",
            "cpp:structure",
            "cpp:testing",
        },
        ((None, ()), "CMakeLists.txt"): {"cpp:build", "cpp:structure", "cpp:libraries"},
        (("msvc", ()), "lib/lib.vcxproj"): {"msvc:toolchain"},
        (("msvc", ("win32",)), "app/app.vcxproj"): {
            "msvc:toolchain",
            "win32:overview",
            "win32:style",
        },
    }
    for ((toolchain, selected_apis), path), expected in cases.items():
        actual = skills_for(toolchain, selected_apis, path)
        if actual != expected:
            print(
                f"unexpected skills for {toolchain}/{selected_apis}:{path}: "
                f"{sorted(actual)}"
            )
            return 1
    print("skill-route generator self-test passed")
    return 0


def checked_asset_path(root: Path, path: Path) -> None:
    if not path.resolve().is_relative_to(root.resolve()) or any(
        parent.is_symlink() or parent.is_junction()
        for parent in (path, *path.parents)
        if parent.is_relative_to(root)
    ):
        raise ValueError(f"Scaffold asset escapes its owned root: {path}")


def scaffold_assets(root: Path) -> dict[Path, bytes]:
    shared = root / ".agents/cpp/assets/scaffold/templates"
    if not shared.is_dir():
        raise ValueError(f"Shared scaffold templates are missing: {shared}")
    result: dict[Path, bytes] = {}
    for namespace in ("gpp", "msvc", "win32"):
        assets = root / f".agents/{namespace}/skills/scaffold/assets"
        for source in sorted(shared.rglob("*")):
            if source.is_file():
                checked_asset_path(root, source)
                result[assets / "shared/templates" / source.relative_to(shared)] = (
                    source.read_bytes()
                )
        if namespace != "win32":
            result[assets / "templates/.agents/skill-routes.json.in"] = rendered(
                namespace
            ).encode()
        else:
            for toolchain in TOOLCHAINS:
                result[assets / f"routes/{toolchain}.json"] = rendered(
                    toolchain, ["win32"]
                ).encode()
                result[assets / f"routes/console/{toolchain}.json"] = rendered(
                    toolchain
                ).encode()
    return result


def prepare_scaffolds(root: Path, check: bool) -> int:
    expected = scaffold_assets(root)
    owned = set(expected)
    for namespace in ("gpp", "msvc", "win32"):
        shared = root / f".agents/{namespace}/skills/scaffold/assets/shared/templates"
        if shared.is_dir():
            owned.update(path for path in shared.rglob("*") if path.is_file())
    routes_root = root / ".agents/win32/skills/scaffold/assets/routes"
    if routes_root.is_dir():
        owned.update(path for path in routes_root.rglob("*") if path.is_file())
    for path in owned:
        checked_asset_path(root, path)
    stale = [
        path
        for path in sorted(owned)
        if path not in expected
        or not path.is_file()
        or path.read_bytes() != expected[path]
    ]
    if check:
        for path in stale:
            print(f"STALE: {path.relative_to(root)}")
        return int(bool(stale))
    for path in stale:
        if path not in expected:
            path.unlink()
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[path])
    print(f"prepared {len(expected)} scaffold assets")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--toolchain", choices=TOOLCHAINS)
    parser.add_argument("--api", action="append", choices=APIS, default=[])
    parser.add_argument("--into", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--scaffold-assets", action="store_true")
    args = parser.parse_args()
    if args.scaffold_assets:
        if any((args.toolchain, args.api, args.into, args.self_test)):
            parser.error("--scaffold-assets accepts only --check")
        return prepare_scaffolds(Path(__file__).resolve().parents[1], args.check)
    if args.self_test:
        if any((args.toolchain, args.api, args.into, args.check)):
            parser.error("--self-test cannot be combined with generation arguments")
        return self_test()
    if not args.into:
        parser.error("--into is required")
    toolchain, apis = normalize(args.toolchain, args.api)
    return write_or_check(toolchain, list(apis), args.into.resolve(), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
